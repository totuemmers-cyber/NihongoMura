// The words the learner can learn (particles are grammar; a same: entry counts as its main word)
const LEARNABLE_WORDS = VOCABULARY.filter(w => w.type !== 'particle' && !w.same).map(w => w.id);
const WORD_CANON = Object.fromEntries(VOCABULARY.filter(w => w.same).map(w => [w.id, w.same]));
function canonWord(id) { return WORD_CANON[id] || id; }
function knowsWord(person, id) { return person.knownWords.has(canonWord(id)); }

function buildVocab() {
    const v = {};
    for (const c of VOCABULARY) {
        v[c.id] = { kanji: c.kanji, kana: c.kana, romaji: c.romaji, de: c.de, type: c.type, vclass: c.vclass, same: c.same };
    }
    return v;
}
